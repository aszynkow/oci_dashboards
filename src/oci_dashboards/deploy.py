def prepare(config, output):
    output = Path(output).resolve()
    output.mkdir(parents=True, exist_ok=True)
    output.chmod(0o700)
    identity = {'mode': 'native-events-v1', 'tenancy_id': config['iam_policy_compartment_id'],
        'region': config['region'], 'telemetry_compartment_id': config['telemetry_compartment_id'],
        'scope_id': config['scope_id']}
    identity_file = output/'deployment-identity.json'
    if identity_file.exists() and json.loads(identity_file.read_text()) != identity:
        raise ValueError('Output directory belongs to another deployment or legacy collector state; use a separate output directory and review migration without deleting state')
    write_json(identity_file, identity)
    payload = build(config, display_name=config.get('dashboard_display_name'))
    write_json(output/'dashboard.management.json', payload)
    write_json(output/'dashboard.management.api.json', api_payload(payload))
    definition = schema(config['scope_id'])
    definition['example'] = example_event()  # Parser example only, never uploaded as log data.
    write_json(output/'native-event-schema.json', definition)
    write_json(output/'terraform/main.tf.json', terraform_stack(config, output))
    summary = {'mode': 'prepare-only', **identity, 'home_region': 'discovered by Terraform',
        'namespace': 'discovered by Terraform', 'create_iam_policy': config['create_iam_policy'],
        'widgets': 15, 'source_compartments': config['inventory_compartment_ids'],
        'flow': ['native backup end Events', 'Streaming', 'Connector Hub', 'Log Analytics', 'native saved searches/dashboard'],
        'limitations': ['recorded operation outcomes only; no recoverability assessment',
                        'no events can mean quiet activity or broken ingestion; investigate service health']}
    write_json(output/'deployment-design.json', summary)
    return summary


def preflight(config):
    for key in ('telemetry_compartment_id', 'dashboard_compartment_id', 'inventory_compartment_ids',
                'iam_policy_compartment_id', 'alarm_destination_topic_ids', 'region', 'scope_id', 'existing_stream_id'):
        if re.search(r'REPLACE|SYNTHETIC|CHANGEME', json.dumps(config.get(key)), re.IGNORECASE):
            raise ValueError('Replace placeholder identifiers before plan/apply: ' + key)


def reject_deletions(plan):
    bad = []
    for item in plan.get('resource_changes', []):
        change = item['change']
        if 'delete' not in change['actions']:
            continue
        # Management import wrapper Delete is documented/verified a no-op.
        if item.get('type') == 'oci_management_dashboard_management_dashboards_import' and 'create' in change['actions']:
            continue
        # The legacy local marker is now inert. Its replacement only updates
        # Terraform metadata; it has no provisioners or remote side effects.
        if (item.get('type') == 'terraform_data' and item.get('address') == 'module.central.terraform_data.native_schema'
            and 'create' in change['actions'] and all(
                ((change.get(side) or {}).get('input') or {}).get('owner') == 'oci-dashboards-native-schema-v1'
                for side in ('before', 'after'))):
            continue
        bad.append(item['address'])
    if bad:
        raise ValueError('Deployment refuses resource deletion/replacement: ' + ', '.join(bad))


def plan_stack(output, execute=run):
    prefix = ['terraform', '-chdir='+str(output/'terraform')]
    # Absolute file:// module sources are copied into .terraform/modules. Refresh
    # those copies before each plan; retain provider lock versions.
    execute(prefix+['get', '-update'])
    execute(prefix+['init', '-input=false'])
    execute(prefix+['validate'])
    execute(prefix+['plan', '-input=false', '-out=deployment.tfplan'])
    plan = json.loads(execute(prefix+['show', '-json', 'deployment.tfplan'], capture=True).stdout)
    reject_deletions(plan)
    write_json(output/'terraform-plan.json', plan)
    return prefix


def setup_schema(config, output):
    """Apply-only Python SDK phase, after deletion checks and before TF apply."""
    from .native_schema import install, NativeSchemaError
    import oci
    plan = json.loads((output/'terraform-plan.json').read_text())
    namespace = ((plan.get('planned_values') or {}).get('outputs') or {}).get('log_analytics_namespace') or {}
    namespace = namespace.get('value')
    if not isinstance(namespace, str) or not namespace.strip():
        raise NativeSchemaError('Reviewed Terraform plan did not resolve the Log Analytics namespace; no schema setup or apply was run')
    try:
        sdk_config = oci.config.from_file(profile_name=config['oci_profile'])
    except Exception:
        raise NativeSchemaError('Cannot load selected OCI profile for Python schema setup') from None
    if sdk_config.get('tenancy') != config['iam_policy_compartment_id'] or sdk_config.get('region') != config['region']:
        raise NativeSchemaError('OCI profile tenancy/region changed after planning; prepare and plan again')
    definition = json.loads((output/'native-event-schema.json').read_text())
    if definition.get('scope_id') != config['scope_id'] or definition.get('source') != names(config['scope_id'])['source']:
        raise NativeSchemaError('Generated schema does not match the deployment scope')
    client = oci.log_analytics.LogAnalyticsClient(sdk_config, retry_strategy=oci.retry.NoneRetryStrategy())
    install(client, namespace, config['iam_policy_compartment_id'], definition, oci.log_analytics.models,
            before_parser_upsert=lambda parser: record_parser_request(client, parser, output),
            before_source_upsert=lambda source: record_schema_request(client, source, output, 'source'))


def record_parser_request(client, parser, output):
    record_schema_request(client, parser, output, 'parser')


def record_schema_request(client, payload, output, kind):
    """Capture only the SDK-serialized schema body; never signed HTTP headers."""
    if kind not in ('parser', 'source'):
        raise ValueError('Unsupported schema request kind')
    import hashlib
    from datetime import datetime, timezone
    path = output/(kind+'-upsert.request.json')
    write_json(path, client.base_client.sanitize_for_serialization(payload))
    write_json(output/(kind+'-upsert.request.metadata.json'), {
        'captured_at': datetime.now(timezone.utc).isoformat(),
        'operation': 'upsert_'+kind, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
        'note': 'Request body captured before SDK send; does not prove API acceptance or persistence.'})
    print(kind.capitalize()+' request body saved locally: ' + str(path), flush=True)


def main(argv=None):
    parser = argparse.ArgumentParser(description='Prepare, plan or deploy native OCI backup event activity dashboard')
    parser.add_argument('--tfvars', default=str(ROOT/'terraform/terraform.tfvars'))
    parser.add_argument('--profile', help='Existing API-key profile in ~/.oci/config; default is DEFAULT')
    parser.add_argument('--output', default=str(ROOT/'build/native-events'))
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--prepare', action='store_true', help='Offline generation (default); no OCI calls')
    mode.add_argument('--plan', action='store_true', help='Read cloud metadata and save a Terraform plan; no upserts/apply')
    mode.add_argument('--apply', action='store_true', help='Run Python schema setup, then apply the reviewed Terraform plan')
    args = parser.parse_args(argv)
    config = load_tfvars_settings(args.tfvars, profile=args.profile)
    output = Path(args.output).resolve()
    if not output.is_relative_to(ROOT/'build'):
        parser.error('--output must be under this repository build/ directory')
    output.mkdir(parents=True, exist_ok=True)
    output.chmod(0o700)
    with (output/'.deployment.lock').open('w') as lock:
        (output/'.deployment.lock').chmod(0o600)
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise ValueError('Another deployment is using this output directory') from None
        summary = prepare(config, output)
        if not args.plan and not args.apply:
            print(json.dumps(summary, indent=2))
            return 0
        preflight(config)
        prefix = plan_stack(output)
        if args.plan:
            print('Plan saved; no resources deployed.')
            return 0
        # Every cloud mutation is behind explicit apply. Schema setup is direct
        # Python, independent of Terraform provisioners; failure stops TF apply.
        print('Configuring and testing Log Analytics schema with Python...', flush=True)
        setup_schema(config, output)
        print('Schema setup complete; applying reviewed Terraform plan...', flush=True)
        run(prefix+['apply', '-input=false', 'deployment.tfplan'])
        outputs = json.loads(run(prefix+['output', '-json'], capture=True).stdout)
        receipt = {key: value['value'] for key, value in outputs.items()}
        receipt.update(region=config['region'], scope_id=config['scope_id'], mode='native-events-v1', schema_managed_by='python_deployer')
        write_json(output/'receipt.json', receipt)
        print(json.dumps(receipt, indent=2))
        return 0


if __name__ == '__main__':
    raise SystemExit(main())
