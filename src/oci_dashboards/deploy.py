ROOT = Path(__file__).resolve().parents[2]
OUTPUTS = ('analytics_log_group_id', 'connector_id', 'stream_id', 'event_rule_ids', 'home_region',
           'log_analytics_namespace', 'tenancy_namespace', 'native_source_name',
           'events_iam_statements', 'connector_iam_statements', 'alarm_destination_topic_ids')


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + '.tmp')
    temporary.write_text(json.dumps(value, indent=2, ensure_ascii=False) + '\n')
    temporary.chmod(0o600)
    temporary.replace(path)


def run(argv, *, capture=False):
    print('+ ' + shlex.join(str(arg) for arg in argv), flush=True)
    return subprocess.run([str(arg) for arg in argv], check=True, text=True, capture_output=capture,
        env={key: value for key, value in os.environ.items()
             if not key.startswith(('TF_VAR_', 'TF_CLI_ARGS', 'TF_LOG'))})


def profile_metadata(profile):
    import oci
    try:
        config = oci.config.from_file(profile_name=profile)
    except Exception:
        raise ValueError('Cannot load selected OCI profile from ~/.oci/config') from None
    if not config.get('region') or not str(config.get('tenancy', '')).startswith('ocid1.tenancy.'):
        raise ValueError('Selected OCI profile must contain region and a tenancy OCID')
    return {'region': config['region'], 'tenancy': config['tenancy']}


def load_tfvars_settings(path, *, profile=None):
    values = load(path, overrides={'oci_profile': profile} if profile else None)
    for name in ('dashboard_import_file', 'native_source_name'):
        if values.get(name):
            raise ValueError(name + ' is generated by deploy.py; omit it from tfvars')
    selected = profile or values['oci_profile']
    if not selected.strip():
        raise ValueError('OCI profile must not be empty')
    metadata = profile_metadata(selected)
    values.update(oci_profile=selected, region=metadata['region'], home_region=None,
                  iam_policy_compartment_id=metadata['tenancy'])
    values['dashboard_compartment_id'] = values['dashboard_compartment_id'] or values['telemetry_compartment_id']
    validate(values)
    return values


def terraform_stack(config, output):
    central = {key: config[key] for key in ('oci_profile', 'region', 'iam_policy_compartment_id',
        'telemetry_compartment_id', 'dashboard_compartment_id', 'inventory_compartment_ids', 'scope_id',
        'create_iam_policy', 'log_analytics_namespace', 'alarm_destination_topic_ids', 'stream_retention_hours', 'existing_stream_id')}
    central.update(source=str(ROOT/'terraform'),
        dashboard_import_file=str(output/'dashboard.management.api.json'),
        native_source_name=names(config['scope_id'])['source'])
    return {'terraform': {'required_version': '>= 1.5.0',
                         'required_providers': {'oci': {'source': 'oracle/oci'}}},
            'module': {'central': central},
            'output': {key: {'value': '${module.central.'+key+'}'} for key in OUTPUTS}}


